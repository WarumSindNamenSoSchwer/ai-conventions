"""Project and machine setup for MCS conventions. Used by bin/mcs.

Everything setup writes into a project sits between markers or under keys it
owns, so uninstall removes exactly that and nothing else.
"""

import copy
import filecmp
import json
import os
import re
import shutil
import sys
from pathlib import Path

MCS = Path(__file__).resolve().parent.parent
BEGIN = "<!-- mcs:begin (generated by .mcs setup, do not edit) -->"
END = "<!-- mcs:end -->"
RULE_FILES = ("AGENTS.md", "rules/general.md", "rules/agents.md", "rules/embedded.md", "rules/c-cpp.md")
GITATTR_LINE = "Docs/Plans/*.md text eol=lf"
GITIGNORE_LINE = ".mcs-guard.log"
SKILLS = ("mcs-plan",)
MARKETPLACE = "mcs"
AUTOCOMPACT = ("CLAUDE_AUTOCOMPACT_PCT_OVERRIDE", "70")
DENY = [
    "Bash(JLinkExe *)", "Bash(JLinkGDBServer *)", "Bash(openocd *)", "Bash(pyocd *)",
    "Bash(probe-rs *)", "Bash(nrfjprog *)", "Bash(st-flash *)", "Bash(commander flash *)",
    "Bash(gh pr merge *)", "Bash(git push origin main)", "Bash(git push origin develop)",
    "Bash(mcs approve *)", "Bash(.mcs/bin/mcs approve *)",
]
DISPATCH_NAME = "mcs-dispatch.py"


# -- small file helpers ------------------------------------------------------

def read(path):
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def remove_if_empty(path):
    if path.is_file() and not read(path).strip():
        path.unlink()
    elif path.is_dir() and not any(path.iterdir()):
        path.rmdir()


def set_block(path, content):
    """Insert or replace the marker block; keep everything else as is."""
    text = read(path)
    block = f"{BEGIN}\n{content.rstrip()}\n{END}\n"
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = block + ("\n" + text if text else "")
    write(path, text)


def drop_block(path):
    text = read(path)
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?\n?", re.S)
    if path.is_file():
        write(path, pattern.sub("", text))
        remove_if_empty(path)


def get_block(path):
    m = re.search(re.escape(BEGIN) + r"\n(.*?)\n" + re.escape(END), read(path), re.S)
    return m.group(1) if m else None


def add_line(path, line):
    text = read(path)
    if line not in text.splitlines():
        write(path, text + ("" if not text or text.endswith("\n") else "\n") + line + "\n")


def drop_line(path, line):
    if path.is_file():
        lines = [l for l in read(path).splitlines() if l != line]
        write(path, "\n".join(lines) + ("\n" if lines else ""))
        remove_if_empty(path)


# -- project content ---------------------------------------------------------

def claude_md_block():
    return "\n".join("@.mcs/" + f for f in RULE_FILES)


def jcode_overlay_block():
    """Jcode does not expand @imports, so the rules are inlined."""
    parts = []
    for f in RULE_FILES:
        text = read(MCS / f).replace("](rules/", "](.mcs/rules/")
        parts.append(f"<!-- source: .mcs/{f} -->\n{text.strip()}")
    return "\n\n".join(parts)


def hooks_snippet():
    return json.loads(read(MCS / "adapters" / "claude-code" / "hooks.json"))["hooks"]


def plugin_names(include_disabled=False):
    data = json.loads(read(MCS / ".claude-plugin" / "marketplace.json") or "{}")
    return [p["name"] for p in data.get("plugins", [])
            if include_disabled or p.get("defaultEnabled", True)]


def is_ours_hook(entry):
    return any("/.mcs/" in h.get("command", "") for h in entry.get("hooks", []))


def merge_settings(settings):
    s = copy.deepcopy(settings)
    s.setdefault("extraKnownMarketplaces", {})[MARKETPLACE] = {
        "source": {"source": "directory", "path": ".mcs"}}
    enabled = s.setdefault("enabledPlugins", {})
    for name in plugin_names():
        enabled[f"{name}@{MARKETPLACE}"] = True
    deny = s.setdefault("permissions", {}).setdefault("deny", [])
    deny.extend(d for d in DENY if d not in deny)
    s.setdefault("env", {}).setdefault(*AUTOCOMPACT)
    hooks = s.setdefault("hooks", {})
    for event, entries in hooks_snippet().items():
        kept = [e for e in hooks.get(event, []) if not is_ours_hook(e)]
        hooks[event] = kept + entries
    return s


def strip_settings(settings):
    s = copy.deepcopy(settings)
    s.get("extraKnownMarketplaces", {}).pop(MARKETPLACE, None)
    for key in list(s.get("enabledPlugins", {})):
        if key.endswith("@" + MARKETPLACE):
            del s["enabledPlugins"][key]
    if "permissions" in s and "deny" in s["permissions"]:
        s["permissions"]["deny"] = [d for d in s["permissions"]["deny"] if d not in DENY]
        if not s["permissions"]["deny"]:
            del s["permissions"]["deny"]
    if s.get("env", {}).get(AUTOCOMPACT[0]) == AUTOCOMPACT[1]:
        del s["env"][AUTOCOMPACT[0]]
    for event in list(s.get("hooks", {})):
        s["hooks"][event] = [e for e in s["hooks"][event] if not is_ours_hook(e)]
        if not s["hooks"][event]:
            del s["hooks"][event]
    return {k: v for k, v in s.items() if v not in ({}, [])}


def load_json(path):
    try:
        return json.loads(read(path)) if path.is_file() else {}
    except ValueError:
        raise SystemExit(f"cannot parse {path}; fix it by hand and rerun setup")


def save_json(path, data):
    if data:
        write(path, json.dumps(data, indent=2) + "\n")
    elif path.is_file():
        path.unlink()


# -- Jcode dispatcher (machine-wide) ----------------------------------------

def jcode_home():
    return Path(os.environ.get("JCODE_HOME") or Path.home() / ".jcode")


def dispatch_paths():
    hooks = jcode_home() / "hooks"
    return hooks / DISPATCH_NAME, hooks / "mcs-dispatch.json", jcode_home() / "config.toml"


def load_state():
    _, state_path, _ = dispatch_paths()
    try:
        return json.loads(read(state_path)) if state_path.is_file() else {}
    except ValueError:
        return {}


def save_state(state):
    _, state_path, _ = dispatch_paths()
    write(state_path, json.dumps(state, indent=2) + "\n")


HOOKS_HEADER = re.compile(r"^\s*\[hooks\]\s*(#.*)?$")
ANY_HEADER = re.compile(r"^\s*\[")
PRE_TOOL = re.compile(r"^\s*pre_tool\s*=\s*(.*?)\s*(#.*)?$")


def _toml_string(raw):
    raw = raw.strip()
    if raw.startswith("'") and raw.endswith("'"):
        return raw[1:-1]
    if raw.startswith('"') and raw.endswith('"'):
        return json.loads(raw)
    return raw


def read_pre_tool(config_text):
    """Return (line_index, value) of [hooks] pre_tool, or (None, '')."""
    in_hooks = False
    for i, line in enumerate(config_text.splitlines()):
        if HOOKS_HEADER.match(line):
            in_hooks = True
        elif ANY_HEADER.match(line):
            in_hooks = False
        elif in_hooks:
            m = PRE_TOOL.match(line)
            if m:
                return i, _toml_string(m.group(1))
    return None, ""


def dispatch_command():
    """Command for [hooks] pre_tool. Uses the base interpreter, not a venv that
    may be deleted later: Jcode fails open, so a missing Python means no guard."""
    dispatch, _, _ = dispatch_paths()
    exe = getattr(sys, "_base_executable", None) or sys.executable
    py = Path(exe).as_posix()
    return f'"{py}" "{dispatch.as_posix()}"'


def dispatch_python(value):
    m = re.match(r'\s*"([^"]+)"', value)
    return m.group(1) if m else ""


def install_dispatcher(root):
    dispatch, _, config = dispatch_paths()
    state = load_state()
    text = read(config)
    lines = text.splitlines()
    idx, value = read_pre_tool(text)
    ours = DISPATCH_NAME in value
    if "config_backup" not in state:
        state["config_backup"] = {"line": lines[idx] if idx is not None else None,
                                  "previous": "" if ours else value,
                                  "added_section": False, "existed": config.is_file()}
    if not ours:
        state["previous"] = value
    new_line = "pre_tool = " + json.dumps(dispatch_command())
    if idx is not None:
        lines[idx] = new_line
    else:
        header = next((i for i, l in enumerate(lines) if HOOKS_HEADER.match(l)), None)
        if header is None:
            lines += ([""] if lines and lines[-1].strip() else []) + ["[hooks]"]
            state["config_backup"]["added_section"] = True
            header = len(lines) - 1
        lines.insert(header + 1, new_line)
    write(config, "\n".join(lines) + "\n")
    dispatch.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(MCS / "adapters" / "jcode" / "dispatch.py", dispatch)
    projects = state.setdefault("projects", [])
    if str(root) not in projects:
        projects.append(str(root))
    save_state(state)


def remove_dispatcher(root):
    dispatch, state_path, config = dispatch_paths()
    state = load_state()
    if not state:
        return "Jcode dispatcher: not installed"
    # Keep every other registered project unless its directory is gone; a
    # project with a temporarily missing submodule still counts as a user.
    projects = [p for p in state.get("projects", []) if p != str(root) and Path(p).is_dir()]
    if projects:
        state["projects"] = projects
        save_state(state)
        return f"Jcode dispatcher kept: still used by {len(projects)} project(s)"
    backup = state.get("config_backup", {})
    text = read(config)
    lines = text.splitlines()
    idx, value = read_pre_tool(text)
    if idx is not None and DISPATCH_NAME in value:
        if backup.get("line") is not None:
            lines[idx] = backup["line"]
        else:
            del lines[idx]
            if backup.get("added_section"):
                h = next((i for i, l in enumerate(lines) if HOOKS_HEADER.match(l)), None)
                section_empty = h is not None and (h + 1 == len(lines) or ANY_HEADER.match(lines[h + 1]))
                if section_empty:
                    del lines[h]
                    if h > 0 and not lines[h - 1].strip():
                        del lines[h - 1]
        if lines or backup.get("existed"):
            write(config, "\n".join(lines) + ("\n" if lines else ""))
        elif config.is_file():
            config.unlink()
    for p in (dispatch, state_path):
        if p.is_file():
            p.unlink()
    remove_if_empty(dispatch.parent)
    return "Jcode dispatcher removed, previous pre_tool restored"


def project_uses_mcs(root):
    return (root / ".mcs" / "guard" / "guard.py").is_file()


# -- commands ---------------------------------------------------------------

def target_root():
    if MCS.name != ".mcs":
        raise SystemExit(f"setup must run from the project's .mcs submodule, not {MCS}")
    return MCS.parent


def install_claude_plugins(root):
    """Claude Code fetches plugins with an external source only after an explicit
    install on each machine. Best effort: without the CLI, print the commands."""
    names = plugin_names()
    claude = shutil.which("claude")
    if not claude:
        return [f"claude plugin install {n}@{MARKETPLACE} --scope project" for n in names]
    import subprocess
    failed = []
    subprocess.run([claude, "plugin", "marketplace", "add", "./.mcs", "--scope", "project"], cwd=root,
                   capture_output=True, text=True, timeout=120)
    for n in names:
        out = subprocess.run([claude, "plugin", "install", f"{n}@{MARKETPLACE}", "--scope", "project"],
                             cwd=root, capture_output=True, text=True, timeout=300)
        if "Successfully installed" not in out.stdout + out.stderr and "already installed" not in (out.stdout + out.stderr):
            failed.append(f"claude plugin install {n}@{MARKETPLACE} --scope project")
    return failed


def uninstall_claude_plugins(root):
    claude = shutil.which("claude")
    if not claude:
        return
    import subprocess
    for n in plugin_names(include_disabled=True):
        subprocess.run([claude, "plugin", "uninstall", f"{n}@{MARKETPLACE}", "--scope", "project"],
                       cwd=root, capture_output=True, text=True, timeout=120)
    subprocess.run([claude, "plugin", "marketplace", "remove", MARKETPLACE], cwd=root,
                   capture_output=True, text=True, timeout=120)


def cmd_setup(args):
    root = target_root()
    set_block(root / "CLAUDE.md", claude_md_block())
    set_block(root / ".jcode" / "prompt-overlay.md", jcode_overlay_block())
    settings_path = root / ".claude" / "settings.json"
    save_json(settings_path, merge_settings(load_json(settings_path)))
    add_line(root / ".gitattributes", GITATTR_LINE)
    add_line(root / ".gitignore", GITIGNORE_LINE)
    for skill in SKILLS:
        dst = root / ".jcode" / "skills" / skill
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(MCS / "plugins" / "mcs" / "skills" / skill, dst)
    (root / "Docs" / "Plans").mkdir(parents=True, exist_ok=True)
    if "--no-jcode" not in args:
        install_dispatcher(root)
    todo = [] if ("--no-plugins" in args or os.environ.get("MCS_NO_PLUGINS")) else install_claude_plugins(root)
    # claude may rewrite the settings file; keep our merge authoritative
    save_json(settings_path, merge_settings(load_json(settings_path)))
    print(f"mcs setup: done in {root}")
    if todo:
        print("Claude Code plugins not installed yet; run in the project:")
        for c in todo:
            print(f"  {c}")
    print("Claude Code: open the project and trust the folder.")
    print("Jcode: rules via .jcode/prompt-overlay.md, guard via the pre_tool dispatcher.")
    return 0


def cmd_uninstall(args):
    root = target_root()
    if not ("--no-plugins" in args or os.environ.get("MCS_NO_PLUGINS")):
        uninstall_claude_plugins(root)
    drop_block(root / "CLAUDE.md")
    drop_block(root / ".jcode" / "prompt-overlay.md")
    settings_path = root / ".claude" / "settings.json"
    save_json(settings_path, strip_settings(load_json(settings_path)))
    remove_if_empty(root / ".claude")
    drop_line(root / ".gitattributes", GITATTR_LINE)
    drop_line(root / ".gitignore", GITIGNORE_LINE)
    for skill in SKILLS:
        dst = root / ".jcode" / "skills" / skill
        if dst.exists():
            shutil.rmtree(dst)
    remove_if_empty(root / ".jcode" / "skills")
    remove_if_empty(root / ".jcode")
    plans_dir = root / "Docs" / "Plans"
    remove_if_empty(plans_dir)
    remove_if_empty(root / "Docs")
    print(remove_dispatcher(root))
    print(f"mcs uninstall: done in {root}. The .mcs submodule itself stays; remove it with git.")
    return 0


def check_project(root):
    issues = []
    if get_block(root / "CLAUDE.md") != claude_md_block():
        issues.append("CLAUDE.md import block missing or outdated")
    if get_block(root / ".jcode" / "prompt-overlay.md") != jcode_overlay_block().rstrip():
        issues.append(".jcode/prompt-overlay.md missing or outdated (rules changed in .mcs)")
    settings = load_json(root / ".claude" / "settings.json")
    if merge_settings(settings) != settings:
        issues.append(".claude/settings.json missing MCS hooks, plugins or permissions")
    if GITATTR_LINE not in read(root / ".gitattributes").splitlines():
        issues.append(".gitattributes misses '" + GITATTR_LINE + "'")
    for skill in SKILLS:
        src, dst = MCS / "plugins" / "mcs" / "skills" / skill, root / ".jcode" / "skills" / skill
        if not dst.is_dir() or filecmp.dircmp(src, dst).diff_files or not (dst / "SKILL.md").is_file():
            issues.append(f".jcode/skills/{skill} missing or outdated")
    if jcode_home().is_dir():
        _, value = read_pre_tool(read(dispatch_paths()[2]))
        if DISPATCH_NAME not in value:
            issues.append("Jcode pre_tool dispatcher not installed")
        elif not Path(dispatch_python(value)).is_file():
            issues.append(f"Jcode dispatcher Python missing ({dispatch_python(value)}); rerun setup")
        elif str(root) not in load_state().get("projects", []):
            issues.append("project not registered with the Jcode dispatcher")
    return issues


def check_machine():
    state = load_state()
    _, value = read_pre_tool(read(dispatch_paths()[2]))
    print("Jcode dispatcher: " + ("installed" if DISPATCH_NAME in value else "not installed"))
    if state.get("previous"):
        print(f"previous pre_tool (runs first): {state['previous']}")
    for p in state.get("projects", []):
        print(f"  {p}  [{'ok' if project_uses_mcs(Path(p)) else 'missing'}]")
    return 0
